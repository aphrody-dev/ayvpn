#!/usr/bin/env bun
// ayvpn.toml + the live GitHub API -> forks.toml (the manifest read by rust-mono's tools/forks.ts and tools/submodules.ts).
//   bun tools/discover.ts            write forks.toml
//   bun tools/discover.ts --dry-run  print the selection
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");

export type Repo = { name: string; description?: string | null; primaryLanguage?: { name: string } | null; isArchived: boolean; defaultBranchRef?: { name: string } | null; repositoryTopics?: { name: string }[] | null };
export type Source = { org: string; take: "all" | "match"; languages?: string[]; pattern?: string; extra?: string[] };

export function select(src: Source, repos: Repo[]): Repo[] {
  const re = src.pattern ? new RegExp(src.pattern, "i") : undefined;
  const extra = new Set((src.extra ?? []).filter((e) => e.startsWith(`${src.org}/`)).map((e) => e.split("/")[1]!));
  return repos.filter((r) => {
    if (r.isArchived) return false;
    if (extra.has(r.name) || src.take === "all") return true;
    if (src.languages && !src.languages.includes(r.primaryLanguage?.name ?? "")) return false;
    const text = [r.name, r.description ?? "", ...(r.repositoryTopics ?? []).map((t) => t.name)].join(" ");
    return !!re && re.test(text);
  });
}

/**
 * Fork name: the upstream name when it is free or already is a fork of this very upstream; <owner>-<name> when the organization holds a
 * different repository of that name. `taken` maps a lower-cased repository name to the upstream it forks ("" when it is not a fork).
 */
export const forkName = (owner: string, name: string, taken: Map<string, string>): string => {
  const upstream = `${owner}/${name}`.toLowerCase();
  const hit = taken.get(name.toLowerCase());
  if (hit === undefined || hit === upstream) return name;
  const prefixed = taken.get(`${owner}-${name}`.toLowerCase());
  return prefixed === undefined || prefixed === upstream ? `${owner}-${name}` : `${owner}-${name}-fork`;
};

export function toToml(org: string, entries: { path: string; name: string; upstream: string; branch: string; note?: string }[], generated: string): string {
  const q = (s: string) => JSON.stringify(s);
  const out = [`# Generated by tools/discover.ts on ${generated} from ayvpn.toml; do not edit. Reused by rust-mono's tools/forks.ts and tools/submodules.ts.`, "", "[meta]", `org = ${q(org)}`, "", "[groups]", ...[...new Set(entries.map((e) => e.path.split("/")[0]!))].map((g) => `${g} = ${q(`forks of the ${g} organization`)}`), ""];
  for (const e of entries) out.push("[[fork]]", `path = ${q(e.path)}`, `name = ${q(e.name)}`, `upstream = ${q(e.upstream)}`, `branch = ${q(e.branch)}`, 'role = "consumer"', "");
  return out.join("\n");
}

const gh = (...args: string[]): unknown => {
  const p = Bun.spawnSync(["gh", ...args], { stdout: "pipe", stderr: "pipe" });
  if (p.exitCode !== 0) throw new Error(`gh ${args.join(" ")}: ${p.stderr.toString().slice(0, 200)}`);
  return JSON.parse(p.stdout.toString());
};

if (import.meta.main) {
  const cfg = Bun.TOML.parse(await Bun.file(join(root, "ayvpn.toml")).text()) as { product: { forks: string }; source: Source[] };
  const forksOrg = cfg.product.forks;
  const taken = new Map((gh("repo", "list", forksOrg, "--limit", "5000", "--json", "name,parent") as { name: string; parent?: { owner: { login: string }; name: string } | null }[]).map((r) => [r.name.toLowerCase(), r.parent ? `${r.parent.owner.login}/${r.parent.name}`.toLowerCase() : ""] as const));
  const entries: { path: string; name: string; upstream: string; branch: string }[] = [];
  for (const src of cfg.source) {
    const repos = gh("repo", "list", src.org, "--limit", "2000", "--json", "name,description,primaryLanguage,isArchived,defaultBranchRef,repositoryTopics") as Repo[];
    for (const r of select(src, repos).sort((a, b) => a.name.localeCompare(b.name))) {
      const upstream = `${src.org}/${r.name}`;
      const name = forkName(src.org, r.name, taken);
      entries.push({ path: `${src.org}/${name}`, name, upstream, branch: r.defaultBranchRef?.name ?? "main" });
    }
  }
  console.log(`${entries.length} repositories selected: ${cfg.source.map((s) => `${s.org} ${entries.filter((e) => e.upstream.startsWith(`${s.org}/`)).length}`).join(", ")}`);
  if (!process.argv.includes("--dry-run")) await Bun.write(join(root, "forks.toml"), toToml(forksOrg, entries, new Date().toISOString().slice(0, 10)));
}
